"""One report per layer: what its own cohorts agree on.

The concentration test is the same code for every layer -- `concentration_test`
takes the layer as an argument -- so there is nothing layer-specific to write
except the schemes each layer is scored under and the caveats each one carries.
This writes those out as docs/layer_<name>.md so each can be read on its own.
"""
import _bootstrap  # noqa: F401

import pandas as pd

from pmap.paths import RESULTS, ROOT, load_config

DOCS = ROOT / "docs"
ALPHA = 0.05

CAVEATS = {
    "proteome": [
        "Eight cohorts, the deepest layer. Call rates range from 14% (PG1) to "
        "88% (PE5) of the genes each one measures, which is why the null gives "
        "every cohort its own flagging rate rather than assuming a shared one.",
        "PE3 ships direction calls with no effect size, so the fold-change "
        "schemes collapse to that call for it.",
    ],
    "phospho": [
        "Three cohorts, each in two normalisations. The two arms are reported "
        "separately and cohorts are counted rather than arms, so running both "
        "never double-counts a cohort.",
        "The protein-adjusted arm concentrates on pathways but never agrees on "
        "a direction across all three cohorts; the raw arm does, and that "
        "directional signal matches the proteome's own.",
    ],
    "genome": [
        "Truncating loss of function only -- no copy number, no missense, no "
        "structural variants. An absent signal means 'not recurrently "
        "truncated', never 'not altered'.",
        "One direction only: a truncation is loss, so this layer can never "
        "support an up-regulation.",
        "GG2 (n=25) produces no enriched pathway under any scheme, so the "
        "gastric side is effectively one cohort.",
        "Scored by its own schemes (g_*), because it has no effect size.",
    ],
    "scrna": [
        "Pseudobulk DESeq2 only: cells are summed per patient per lineage and "
        "tested across patients, so the unit of replication is the patient. "
        "Per-cell Seurat tests were not used.",
        "One vote per study. The same tumour-vs-normal contrast is run inside "
        "each cell lineage, so counting lineages would let a study win on "
        "annotation depth; the lineage that carried the call is kept as "
        "metadata instead.",
        "SG6 is excluded: its minimum padj is 0.168 across 180k rows.",
        "Six gastric studies against one oesophageal, so the tumour-type split "
        "cannot be asked of this layer.",
    ],
}


def main():
    DOCS.mkdir(exist_ok=True)
    conc = pd.read_csv(RESULTS / "concentration.csv")
    arms = pd.read_csv(RESULTS / "arm_summary.csv")
    cfg = load_config("analysis.yaml")
    gen_scheme = (cfg.get("cross_layer_scheme") or {}).get("genome", "g_top200_n2")
    main_scheme = {"proteome": "fdr05", "phospho": "fdr05", "scrna": "fdr05",
                   "genome": gen_scheme}

    for layer in ["proteome", "phospho", "genome", "scrna"]:
        c = conc[conc["layer"] == layer]
        if c.empty:
            print(f"{layer}: no concentration rows, skipped")
            continue
        sc = main_scheme[layer]
        sig = c[(c["conc_padj"] <= ALPHA) & (c["scheme"] == sc)]

        L = [f"# {layer} -- cross-cohort concentration", "",
             "Regenerated by `scripts/14_layer_reports.py`; do not edit by hand.", "",
             "How many independent cohorts of this layer implicate the same "
             "pathway, against a null where each cohort flags pathways at its "
             "own observed rate (Poisson-binomial tail, BH across pathways "
             "within each collection). The method is identical for every layer; "
             f"this one is scored under `{sc}`.", ""]

        L += ["## Cohorts", "", "| cohort | norm | genes called | up | down |",
              "|---|---|---|---|---|"]
        a = arms[(arms["layer"] == layer) & (arms["scheme"] == sc)]
        for r in a.sort_values("dataset").itertuples(index=False):
            L.append(f"| {r.dataset} | {r.norm} | {r.n_genes_called:,} | "
                     f"{r.n_up:,} | {r.n_down:,} |")

        L += ["", f"## Concentrated pathways (FDR <= {ALPHA})", "",
              "| scheme | norm | direction | pathways |", "|---|---|---|---|"]
        for r in (c[c["conc_padj"] <= ALPHA].groupby(["scheme", "norm", "direction"])
                  .size().rename("n").reset_index().itertuples(index=False)):
            L.append(f"| {r.scheme} | {r.norm} | {r.direction} | {r.n} |")

        for d in ["up", "down", "any"]:
            s = sig[sig["direction"] == d]
            if s.empty:
                continue
            L += ["", f"### Top, {d} ({sc})", "",
                  "| collection | pathway | cohorts | testable | expected | FDR |",
                  "|---|---|---|---|---|---|"]
            for r in s.nsmallest(12, "conc_p").itertuples(index=False):
                L.append(f"| {r.collection} | {r.pathway} | "
                         f"{r.n_cohorts_enriched} | {r.n_cohorts_testable} | "
                         f"{r.expected_cohorts:.2f} | {r.conc_padj:.2e} |")

        L += ["", "## What to keep in mind", ""]
        L += [f"- {t}" for t in CAVEATS[layer]]
        L += ["", "Full table: `results/concentration.csv` "
                  "(every scheme and direction, not just the ones above)."]
        p = DOCS / f"layer_{layer}.md"
        p.write_text("\n".join(L) + "\n", encoding="utf-8")
        print(f"{layer:9s} {len(sig):4d} concentrated at {sc} -> {p.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
